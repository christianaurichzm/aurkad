/**
 * Raises a counter above the ids already in a collection. Documents arrive
 * through the counter (editor "create") and through content files or a
 * seed with their own ids, which leave it alone: after a pack with items
 * 1-8, the editor's next item would get id 1 and be upserted over the
 * pack's. Never lowers it, since a gap is harmless and a reused id is not.
 */
export async function raiseCounter(
  name: 'item' | 'npc' | 'map' | 'arrow' | 'spell',
  highestId: number,
): Promise<void> {
  if (!Number.isFinite(highestId) || highestId <= 0) return;
  await Counter.findByIdAndUpdate(
    name,
    { $max: { seq: Math.floor(highestId) } },
    { upsert: true },
  );
}

/**
 * The next id for a collection that predates its counter, given the highest
 * id already in it.
 *
 * The highest id alone is no allocator: two creations at once read the same
 * one, and the second upsert overwrites the first. The counter is raised to it
 * and then incremented, each an atomic write, so two at once get two ids, and
 * documents that came with their own (a pack, a seed) are stepped over.
 */
export async function getNextIdAbove(
  name: 'arrow' | 'spell',
  highestId: number,
): Promise<number> {
  await raiseCounter(name, highestId);
  const result = await Counter.findByIdAndUpdate(
    name,
    { $inc: { seq: 1 } },
    { upsert: true, returnDocument: 'after' },
  );
  return result.seq;
}

/**
 * The optional fields of `schema` that `value` leaves out. A content save
 * carries the whole entry and is an upsert, whose `$set` only writes the
 * keys present, so these must be `$unset` (and dropped from the live copy)
 * or a cleared field comes back from the stored document.
 */
export function absentOptionalKeys(
  schema: z.ZodObject<Record<string, z.ZodType>>,
  value: object,
): string[] {
  const present = value as Record<string, unknown>;
  return Object.entries(schema.shape)
    .filter(([key, field]) => field.isOptional() && present[key] === undefined)
    .map(([key]) => key);
}

/** `absentOptionalKeys` as the `$unset` of an update, or nothing to unset. */
export function unsetAbsent(
  schema: z.ZodObject<Record<string, z.ZodType>>,
  value: object,
): { $unset?: Record<string, ''> } {
  const keys = absentOptionalKeys(schema, value);
  return keys.length > 0
    ? { $unset: Object.fromEntries(keys.map((key) => [key, ''])) }
    : {};
}
